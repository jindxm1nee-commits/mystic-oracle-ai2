export function drawRandomTarotCard(excludeId?: number): DrawnTarotCard {
  const pool =
    excludeId !== undefined
      ? MAJOR_ARCANA_DECK.filter((c) => c.id !== excludeId)
      : MAJOR_ARCANA_DECK;
  const randomIndex = Math.floor(Math.random() * pool.length);
  const card = pool[randomIndex];
  // 80% Upright (ส่งเสริมโดยตรง), 20% Mindful Alignment (เตือนสติ/ปลดล็อกพลังงาน)
  const isReversed = Math.random() < 0.2;
  return {
    card,
    isReversed,
    orientationLabel: isReversed
      ? 'พลังงานเตือนสติเพื่อปลดล็อก (Shadow Alignment)'
      : 'พลังงานส่งเสริมโดยตรง (Upright Alignment)',
  };
}
